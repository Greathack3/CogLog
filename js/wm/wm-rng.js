/* WM Assessment Platform — reproducible pseudorandom generation (spec §4).

   Every assessment form is generated from a stored seed with a versioned generator, so any
   form can be reconstructed for auditing. Derived per-block / per-trial seeds let a single
   session seed reproduce the entire form deterministically. */
window.WMRng = (function () {
  'use strict';

  /* Bump when generation logic changes in a way that alters output for the same seed.
     Stored on every session and trial so forms generated by different generator versions
     are never silently pooled (spec §4, §11). */
  const VERSION = 'wm-gen-1.0.0';

  /** FNV-1a 32-bit string hash (stable across runs — used for seed derivation + signatures). */
  function hashStr(str) {
    let h = 0x811c9dc5;
    const s = String(str);
    for (let i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      h = Math.imul(h, 0x01000193);
    }
    return h >>> 0;
  }

  /** mulberry32 — small, fast, well-distributed 32-bit PRNG. */
  function mulberry32(a) {
    return function () {
      a |= 0; a = a + 0x6D2B79F5 | 0;
      let t = Math.imul(a ^ a >>> 15, 1 | a);
      t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
      return ((t ^ t >>> 14) >>> 0) / 4294967296;
    };
  }

  /** Create a generator. `seed` is a uint32 (derive children with .derive(label)). */
  function make(seed) {
    const s = seed >>> 0;
    const next = mulberry32(s);
    return {
      seed: s,
      next,
      /** Integer in [lo, hi] inclusive. */
      int(lo, hi) { return lo + Math.floor(next() * (hi - lo + 1)); },
      pick(arr) { return arr[Math.floor(next() * arr.length)]; },
      shuffle(arr) {
        const a = arr.slice();
        for (let i = a.length - 1; i > 0; i--) {
          const j = Math.floor(next() * (i + 1));
          const t = a[i]; a[i] = a[j]; a[j] = t;
        }
        return a;
      },
      chance(p) { return next() < p; },
      /** Child generator deterministically derived from this seed + a label. */
      derive(label) { return make(hashStr(s + '|' + label)); }
    };
  }

  /** Fresh random session seed (crypto when available). */
  function newSeed() {
    try {
      if (window.crypto && crypto.getRandomValues) {
        const a = new Uint32Array(1);
        crypto.getRandomValues(a);
        return a[0] >>> 0;
      }
    } catch (e) { /* fall through */ }
    return (Math.random() * 4294967296) >>> 0;
  }

  function seedToHex(seed) { return '0x' + (seed >>> 0).toString(16).padStart(8, '0'); }

  return { VERSION, hashStr, make, newSeed, seedToHex };
})();
